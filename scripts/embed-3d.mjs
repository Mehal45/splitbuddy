// Packs the 3D models in assets/3d into a TypeScript module of data URIs,
// so the 3D view works offline and inside the single-file preview.
// Run: node scripts/embed-3d.mjs
import fs from "node:fs";
import path from "node:path";
const root = path.resolve("assets/3d");
const out = {};
for (const kit of ["city", "vehicles"]) {
  for (const f of fs.readdirSync(path.join(root, kit))) {
    if (f.endsWith(".glb")) out[`${kit}/${f.replace(/\.glb$/, "")}`] = "data:model/gltf-binary;base64," + fs.readFileSync(path.join(root, kit, f)).toString("base64");
  }
  out[`${kit}/texture`] = "data:image/png;base64," + fs.readFileSync(path.join(root, kit, "Textures/colormap.png")).toString("base64");
}
fs.mkdirSync("src/components/visual", { recursive: true });
fs.writeFileSync("src/components/visual/models3d.ts",
  "// Generated by scripts/embed-3d.mjs from assets/3d (Kenney, MIT licence). Do not edit.\n" +
  "export const MODELS: Record<string, string> = " + JSON.stringify(out, null, 0).replace(/","/g, '",\n  "') + ";\n");
console.log("models:", Object.keys(out).join(", "));
